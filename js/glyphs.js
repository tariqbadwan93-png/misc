// Render a bitmap as an inline SVG string (crisp squares, currentColor).
export function svg(bits, { size = 7, gap = 0 } = {}) {
  const n = bits.length;
  let rects = '';
  for (let r = 0; r < n; r++)
    for (let c = 0; c < bits[r].length; c++)
      if (bits[r][c]) rects += `<rect x="${c}" y="${r}" width="${1 - gap}" height="${1 - gap}"/>`;
  return `<svg viewBox="0 0 ${bits[0].length} ${n}" width="${size}" height="${size}" fill="currentColor" shape-rendering="crispEdges" aria-hidden="true">${rects}</svg>`;
}

// Paint a bitmap into a 2D context at (x, y) with cell size `u`.
export function paint(ctx, bits, x, y, u, alpha = 1) {
  if (alpha <= 0) return;
  const prev = ctx.globalAlpha;
  ctx.globalAlpha = alpha;
  for (let r = 0; r < bits.length; r++) {
    const row = bits[r];
    for (let c = 0; c < row.length; c++) if (row[c]) ctx.fillRect(x + c * u, y + r * u, u, u);
  }
  ctx.globalAlpha = prev;
}
